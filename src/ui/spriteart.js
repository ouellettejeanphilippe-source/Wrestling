// ---------------------------------------------------------------------------
// PLANCHES DE SPRITES DESSINÉES À LA MAIN — FORMAT 16 BITS (24x32)
//
// Chaque sprite est une grille de caractères : un caractère = un pixel. Les
// caractères ne sont pas des couleurs mais des EMPLACEMENTS de palette, donc
// le même dessin habille tout le roster — c'est la méthode « palette swap ».
//
//   .  transparent          K  contour (encre)
//   1  peau ombre profonde  2  peau ombre    3  peau base   4  peau claire   5  peau éclat
//   h  cheveux ombre        H  cheveux base  G  cheveux clair
//   a  tenue ombre          A  tenue base    B  tenue claire
//   n  accent ombre         N  accent base
//   b  bottes ombre         V  bottes base   W  bottes claire
//   e  blanc de l'œil       E  iris          m  bouche
//   w  blanc                o  noir doux (lunettes, sangles)
//
// POURQUOI 24x32. Le format précédent (32x48) donnait trop de pixels : on est
// tenté d'y détailler un torse, et ce détail devient de la bouillie dès que le
// sprite s'affiche à la taille d'une case. Un sprite de Chrono Trigger tient
// dans 24x32, et c'est justement la contrainte qui force des formes franches.
// À surface d'écran égale, chaque pixel est ici 40% plus gros : un visage se
// lit, une tenue se reconnaît.
//
// Pour la même raison, trois tons de peau seulement (ombre, base, clair) : un
// dégradé de cinq tons ne se lit pas à cette résolution, il se salit.
//
// ANATOMIE. 30 lignes debout :
//   1-8   tête et cheveux        9      cou
//   10-18 torse et bras          19-20  short
//   21-26 jambes                 27-30  bottes
// La tête fait 8 lignes sur 30 — le rapport des sprites 16 bits.
//
// Les quatre corps partagent la MÊME boîte crânienne (colonnes 8 à 15, lignes
// 1 à 8) : c'est elle qui garantit qu'une casquette ou une barbe tombe juste
// sur le colosse comme sur le poids léger. Et tous posent le pied sur la même
// ligne, sinon un lutteur sautille d'un pixel quand il se retourne.
//
// Le contour d'encre suit la SILHOUETTE et rien d'autre : un bras cerné sur
// ses quatre côtés donne une poupée articulée. Ici c'est l'ombre qui détache
// le bras du torse.
// ---------------------------------------------------------------------------

