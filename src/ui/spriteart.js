// ---------------------------------------------------------------------------
// PLANCHES DE SPRITES DESSINÉES À LA MAIN
//
// Chaque sprite est une grille de caractères : un caractère = un pixel. Les
// caractères ne sont pas des couleurs mais des EMPLACEMENTS de palette, donc
// le même dessin habille tout le roster — c'est la méthode « palette swap ».
//
//   .  transparent          K  contour (encre)
//   1  peau ombre profonde  2  peau ombre    3  peau base   4  peau claire   5  peau éclat
//   h  cheveux ombre        H  cheveux base  G  cheveux clair
//   a  tenue ombre          A  tenue base    B  tenue claire
//   n  accent ombre         N  accent base
//   b  bottes ombre         V  bottes base   W  bottes claire
//   e  blanc de l'œil       E  iris          m  bouche
//   w  blanc                o  noir doux (lunettes, sangles, encre de tatouage)
//
// ANATOMIE COMMUNE. Les quatre corps partagent la même boîte crânienne —
// crâne colonnes 11 à 21, visage 12 à 20, lignes 2 à 12 — pour qu'une
// casquette ou une barbe tombe juste sur n'importe lequel. Ce qui change en
// dessous, c'est la carrure.
//
// Deux principes tenus dans tous les dessins :
//   · le contour d'encre suit la SILHOUETTE, jamais l'intérieur du corps.
//     Un bras cerné sur ses quatre côtés donne une poupée articulée ; ici
//     c'est l'ombre qui détache le bras du torse.
//   · le colosse est dessiné plus grand DANS LE MÊME CADRE : sa masse vient
//     du dessin, pas d'un agrandissement, donc ses pixels gardent exactement
//     la taille de ceux des autres.
// ---------------------------------------------------------------------------

